UMLAUT = {"ä": "a", "ö": "o", "ü": "u", "Ä": "A", "Ö": "O", "Ü": "U"}


def glyph_rows(ch):
    if ch in UMLAUT:
        base = list(G[UMLAUT[ch]])
        if ch.isupper():
            return [".#.#."] + base[1:]           # dots instead of the top row
        base[0] = ".#.#."
        return base
    return G[ch]


def render(ch):
    rows = glyph_rows(ch)
    rows = rows + ["....."] * (9 - len(rows))
    src = [[c == "#" for c in r] for r in rows]
    w = 6
    bold = [[False] * w for _ in range(9)]
    for y in range(9):
        for x in range(5):
            if not src[y][x]:
                continue
            bold[y][x] = True
            vertical = (y > 0 and src[y - 1][x]) or (y < 8 and src[y + 1][x])
            if vertical:
                bold[y][x + 1] = True        # vertical strokes twice as wide: bold, still readable
    return bold


def main():
    chars = [c for c in G] + list(UMLAUT)
    rows = [chars[i:i + COLS] for i in range(0, len(chars), COLS)]
    img = Image.new("RGBA", (COLS * CELL_W, len(rows) * CELL_H), (0, 0, 0, 0))
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == " ":
                continue
            bm = render(ch)
            # Minecraft keeps empty columns on the left as space: start every glyph at column 0
            left = min((x for x in range(6) if any(bm[y][x] for y in range(9))), default=0)
            bm = [row[left:] + [False] * left for row in bm]
            for y in range(9):
                for x in range(6):
                    if bm[y][x]:
                        img.putpixel((c * CELL_W + x, r * CELL_H + y), (255, 255, 255, 255))
    tex = os.path.join(OUT, "textures", "font", "boxy.png")
    os.makedirs(os.path.dirname(tex), exist_ok=True)
    img.save(tex)
    padded = ["".join(row) + "\u0000" * (COLS - len(row)) for row in rows]
    font = {"providers": [
        {"type": "space", "advances": {" ": 4}},
        {"type": "bitmap", "file": "theprisons:font/boxy.png", "ascent": 7, "height": 9, "chars": padded},
        {"type": "reference", "id": "minecraft:default"},
    ]}
    path = os.path.join(OUT, "font", "boxy.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(font, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print("wrote boxy font with", len(chars), "glyphs")


if __name__ == "__main__":
    main()
